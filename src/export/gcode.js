/**
 * CNC Router G-code Generator with multi-pass stepdown and holding tabs.
 */
export function generateSliceGCode(slice, options = {}) {
  const {
    toolDiameter = 3.175,   // 1/8 inch or 3mm bit
    materialThickness = 6,  // sheet thickness t
    stepDown = 3.0,         // depth per pass in mm
    feedRate = 1800,        // XY cutting feed in mm/min
    plungeRate = 450,       // Z plunge feed in mm/min
    safeZ = 5.0,            // Retract height in mm
    spindleSpeed = 18000,   // RPM
    tabsEnabled = true,
    numTabs = 3,
    tabWidth = 5.0,         // width of tab along cut path in mm
    tabHeight = 2.0         // height of tab remaining from bottom
  } = options;

  const polygon = slice.polygon;
  if (!polygon || polygon.length < 2) return '';

  const totalPasses = Math.ceil(materialThickness / stepDown);
  let gcode = '';

  // Header
  gcode += `; CNC Profile Cut - ${slice.label}\n`;
  gcode += `; Generated by Parametric Wave Logo Slicer\n`;
  gcode += `; Tool Dia: ${toolDiameter}mm, Thickness: ${materialThickness}mm, Passes: ${totalPasses}\n`;
  gcode += `G21 ; Metric mm\n`;
  gcode += `G90 ; Absolute coordinates\n`;
  gcode += `G17 ; XY Plane\n`;
  gcode += `G0 Z${safeZ.toFixed(2)} ; Safe height\n`;
  gcode += `M3 S${spindleSpeed} ; Spindle Start\n`;
  gcode += `G4 P2.0 ; Dwell 2s for spindle ramp-up\n\n`;

  // Start position
  const p0 = polygon[0];
  gcode += `G0 X${p0.x.toFixed(3)} Y${p0.y.toFixed(3)}\n`;

  // Multi-pass profile cutting
  for (let pass = 1; pass <= totalPasses; pass++) {
    const currentZ = -Math.min(materialThickness, pass * stepDown);
    const isFinalPass = (pass === totalPasses);

    gcode += `\n; --- Pass ${pass}/${totalPasses} at Z=${currentZ.toFixed(3)} ---\n`;
    gcode += `G1 Z${currentZ.toFixed(3)} F${plungeRate}\n`;

    // Calculate tab positions along polygon vertices for final pass
    const tabInterval = Math.max(1, Math.floor(polygon.length / (numTabs + 1)));

    for (let i = 1; i < polygon.length; i++) {
      const pt = polygon[i];

      if (isFinalPass && tabsEnabled && (i % tabInterval === 0)) {
        // Tab bridge: lift to tab height
        const tabZ = -(materialThickness - tabHeight);
        gcode += `G1 Z${tabZ.toFixed(3)} F${plungeRate} ; Holding Tab\n`;
        gcode += `G1 X${pt.x.toFixed(3)} Y${pt.y.toFixed(3)} F${feedRate}\n`;
        gcode += `G1 Z${currentZ.toFixed(3)} F${plungeRate}\n`;
      } else {
        gcode += `G1 X${pt.x.toFixed(3)} Y${pt.y.toFixed(3)} F${feedRate}\n`;
      }
    }

    // Close loop back to p0
    gcode += `G1 X${p0.x.toFixed(3)} Y${p0.y.toFixed(3)} F${feedRate}\n`;
  }

  // Footer
  gcode += `\n; --- End Program ---\n`;
  gcode += `G0 Z${safeZ.toFixed(2)} ; Retract tool\n`;
  gcode += `M5 ; Spindle Stop\n`;
  gcode += `G0 X0.000 Y0.000 ; Return home\n`;
  gcode += `M30 ; End Program\n`;

  return gcode;
}
